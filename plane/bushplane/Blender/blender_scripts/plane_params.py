def wing_z_at(frac: float) -> float:
    """Высота линии хорды крыла на доле полуразмаха с учётом поперечного V."""
    return WING_Z_ROOT + math.tan(math.radians(WING_DIHEDRAL)) * frac * WING_SEMI


def wing_chord_at(frac: float) -> float:
    return WING_ROOT_CHORD + (WING_TIP_CHORD - WING_ROOT_CHORD) * frac


def wing_twist_at(frac: float) -> float:
    return WING_INCIDENCE - WING_WASHOUT * frac


def station_at(y: float) -> tuple:
    """Станция фюзеляжа на произвольной координате y (линейная интерполяция)."""
    st = FUSELAGE_STATIONS
    if y >= st[0][0]:
        return st[0]
    if y <= st[-1][0]:
        return st[-1]
    for i in range(len(st) - 1):
        a, b = st[i], st[i + 1]
        if b[0] <= y <= a[0]:
            t = (a[0] - y) / (a[0] - b[0])
            return (y,) + tuple(a[k] + (b[k] - a[k]) * t for k in range(1, len(a)))
    return st[-1]


def cargo_box(margin: float = 0.055) -> tuple[float, float, float]:
    """Полуширина, пол и потолок грузового отсека — из станций фюзеляжа.

    Коробка отсека раньше задавалась тремя числами вручную. Балка к хвосту
    сужается, поэтому при переносе проёма назад такая коробка вылезала бы
    сквозь обшивку, и сквозь борт был бы виден её торец. Считаем по самой
    узкой станции внутри проёма — тогда отсек корректен при любом положении.
    """
    y0, y1 = CARGO_Y
    ys = [y0, (y0 + y1) * 0.5, y1]
    sts = [station_at(y) for y in ys]
    hw = min(s[1] for s in sts) - margin
    floor = max(s[5] - s[3] for s in sts) + margin
    ceil = min(s[5] + s[2] for s in sts) - margin
    return hw, floor, ceil


def fuselage_axis_z(y: float) -> float:
    """Высота осевой линии фюзеляжа — она к хвосту спадает.

    Нужна ливрее: продольная лента должна идти по борту, а не уезжать вниз,
    пока балка клонится.
    """
    ys = [s[0] for s in FUSELAGE_STATIONS]
    zs = [s[5] for s in FUSELAGE_STATIONS]
    if y >= ys[0]:
        return zs[0]
    if y <= ys[-1]:
        return zs[-1]
    for i in range(len(ys) - 1):
        if ys[i + 1] <= y <= ys[i]:
            t = (ys[i] - y) / (ys[i] - ys[i + 1])
            return zs[i] + (zs[i + 1] - zs[i]) * t
    return zs[-1]


