def plural(n, one, few, many):
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def pl(n, *w):
    return f'{n} {plural(n, *w)}'


def fv(v, n=3):
    return '(' + '; '.join(num(a, n) for a in v) + ')'


def num(a, n=2):
    s = f'{a:.{n}f}'.rstrip('0').rstrip('.')
    s = s.replace('.', ',').replace('-', '−')
    return '0' if s in ('−0', '') else s


def thou(k):
    return f'{k:,}'.replace(',', ' ')


