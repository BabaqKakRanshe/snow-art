def tag_wrap(im, text, f=None):
    """MS.tag that breaks a label too wide for the tile onto more lines"""
    from PIL import ImageDraw
    f = f or MS.F(22)
    d = ImageDraw.Draw(im)
    lines = MS.wrap(d, text, f, im.width - 40)
    y = 10
    for line in lines:
        w = d.textlength(line, font=f)
        d.rectangle([4, y - 4, 10 + w + 8, y + f.size + 8], fill=(0, 0, 0))
        d.text((10, y), line, fill=MS.INK, font=f)
        y += f.size + 12


def sheet(title, sub, tiles, rows, fname, cols=2, kw=250):
    """make_sheets_van2.sheet with a wider key column (longer Russian keys)"""
    from PIL import ImageDraw
    W, H, g = 900, 600, 16
    nrow = (len(tiles) + cols - 1) // cols
    S = Image.new('RGB', (cols * W + (cols + 1) * g, 130 + nrow * (H + g) + 900), MS.BG)
    d = ImageDraw.Draw(S)
    d.text((g, 18), title, fill=MS.INK, font=MS.F(50, True))
    d.text((g, 84), sub, fill=MS.DIM, font=MS.F(25))
    for i, (im, label) in enumerate(tiles):
        im = im.copy()
        if im.size != (W, H):
            canvas = Image.new('RGB', (W, H), (10, 10, 12))
            im.thumbnail((W, H), Image.NEAREST)
            canvas.paste(im, ((W - im.width) // 2, (H - im.height) // 2))
            im = canvas
        if label:
            tag_wrap(im, label)
        S.paste(im, (g + (i % cols) * (W + g), 130 + (i // cols) * (H + g)))
    y = 130 + nrow * (H + g) + 18
    f, fb = MS.F(23), MS.F(23, True)
    for k, v in rows:
        d.text((g, y), k, fill=MS.DIM, font=fb)
        yl = y
        for j, line in enumerate(MS.wrap(d, v, f, cols * W + (cols - 1) * g - kw)):
            d.text((g + kw, y + j * 30), line, fill=MS.INK, font=f)
            yl = y + j * 30
        y = yl + 38
    S = S.crop((0, 0, S.width, y + 10))
    p = os.path.join(OUT, fname)
    S.save(p, quality=92)
    return p


