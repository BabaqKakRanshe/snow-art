def fv(v, n=3):
    return '(' + ', '.join(f'{a:.{n}f}'.rstrip('0').rstrip('.').replace('-', '−') if abs(a) > 1e-9 else '0' for a in v) + ')'


def num(a, n=2):
    s = f'{a:.{n}f}'.rstrip('0').rstrip('.')
    return s.replace('.', ',').replace('-', '−')


def thou(n):
    return f'{n:,}'.replace(',', ' ')


