def fv(v, n=3):
    return '(' + ', '.join(f'{round(a, n):g}' for a in v) + ')'


def frange(p):
    r = p.get('range')
    if not r:
        return '—'
    u = {'m': ' м', 'scale': ' ×', 'deg': ' °'}.get(p.get('unit'), '')
    s = f'{r[0]:g}…{r[1]:g}{u}'
    if p['kind'] == 'twist':
        rm = p.get('removable')
        s += {'end': ', потом снять', 'start': ', вынуть в 0'}.get(rm, '')
    return s


