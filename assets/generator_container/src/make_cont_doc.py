        leaf = 'рабочей' if k.startswith('Door_R') else 'левой'
        pos = 'у петель' if k.endswith('_1') else 'у притвора'
        return (f'запорная штанга {leaf} створки ({pos}): поднять ручку из скобы и отвести (+, до 95) — кулачки вверху и '
                f'внизу выходят из упоров на балках; створка свободна, когда выведены обе её штанги')
