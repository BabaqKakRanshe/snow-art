def n(v, d=2):
    s = f'{v:.{d}f}'.rstrip('0').rstrip('.') if d else f'{v:.0f}'
    s = s.replace('-', '−').replace('.', ',')
    return s if s not in ('−0', '') else '0'


def v3(v, d=3):
    return '(' + '; '.join(n(a, d) for a in v) + ')'


def thou(k):
    return f'{k:,}'.replace(',', ' ')


def pl(k, one, few, many):
    k10, k100 = k % 10, k % 100
    w = one if k10 == 1 and k100 != 11 else (few if 2 <= k10 <= 4 and not 12 <= k100 <= 14 else many)
    return f'{k} {w}'


