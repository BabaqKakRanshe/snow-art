def part_rows(item):
    rows = []
    for k in C['items'][item]['parts']:
        p = C['parts'][k]
        if k == item:
            continue
        mv = ''
        if p['kind'] in ('hinge', 'slide', 'spin', 'stretch') and p.get('axis'):
            rg = p.get('range')
            unit = '°' if p.get('unit') == 'deg' else ('' if p.get('unit') == 'x' else ' м')
            d_ = 0 if unit == '°' else (2 if p.get('unit') == 'x' else 3)
            mv = f"ось {v3(p['axis'], 3)}" + (f", {'масштаб ' if p.get('unit') == 'x' else ''}{n(rg[0], d_)}…{n(rg[1], d_)}{unit}"
                                              if rg else '')
            if p.get('rest'):
                mv += f", в начале {n(p['rest'], d_)}{unit}"
        rows.append(f"| `{k}` | {KIND.get(p['kind'], p['kind'])} | {v3(p['pivot'])} | {mv} | {', '.join(p['material'])} |")
    return rows


