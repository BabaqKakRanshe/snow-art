def n(v, d=0):
    """Russian number: groups by a space, decimal comma"""
    return f'{v:,.{d}f}'.replace(',', ' ').replace('.', ',').replace('-', '−')


def pl(k, one, few, many):
    k = abs(int(k))
    if k % 10 == 1 and k % 100 != 11:
        return one
    if k % 10 in (2, 3, 4) and not 12 <= k % 100 <= 14:
        return few
    return many


def nw_(k, one, few, many):
    """'531 место', '3 места', '13 мест'"""
    return f'{n(k)} {pl(k, one, few, many)}'


