def ru_note(name, p):
    if name in RU:
        return RU[name]
    if name.startswith('Engine_Plug_'):
        return f'свеча {name[-1]}: выкрутить (6 оборотов) по оси, сначала снять провод'
    if name.startswith('Engine_Lead_'):
        return f'провод свечи {name[-1]}: колпачок снимается со свечи'
    if name.startswith('Fuse_'):
        k = int(name[5:]) - 1
        return f'предохранитель «{FUSES[k]}» (порядок как на панели тумблеров): ok / сгорел'
    if name.startswith('Seat_') and name.endswith('_Leg'):
        return 'опора сиденья: складывается под сиденье с тем же значением'
    if name.startswith('Seat_'):
        return 'откидное сиденье: к стене на 90°' + ('; под ним ящик АКБ' if name == 'Seat_L4' else '')
    if name.startswith('Needle_'):
        sc = p.get('scale')
        tail = ''
        if sc:
            fv = lambda v: (f'{v:g}').replace('.', ',')
            tail = (f'; шкала {fv(sc["min"])}…{fv(sc["max"])} {sc["unit"]} ↔ {sc["angle_min"]}…{sc["angle_max"]}°; '
                    f'в модели стоит на {fv(p["rest"])}°')
        return ('стрелка прибора: угол от «12 часов», плюс — по часовой (ось в панель); повернуть на угол(значение) − rest'
                + tail)
    if name.startswith('Spare_Fuse_'):
        return 'запасной предохранитель: подходит в любое гнездо Fuse_N'
    if name.startswith('Toggle_'):
        t = name[7:]
        return (f'тумблер «{TOG.get(t, t)}» (вверх — включён), предохранитель {p.get("fuse", "")}: ' +
                ', '.join(p.get('controls', [])))
    if name.startswith('Lock_'):
        return f'кнопка блокировки двери {name[5:]}: утоплена — дверь не открыть снаружи'
    if name.startswith('Wheel_') and '_Nut_' in name:
        return 'гайка колеса: три оборота против часовой баллонником, потом снимается (предмет)'
    if name.startswith('Wheel_'):
        return ('колесо: вращение вокруг +y (плюс — катится вперёд), радиус 0,364 м, ширина 0,343 м, ход подвески 0,10 м; '
                'снимается, когда сняты шесть гаек; блендшейп Flat — спущенная шина')
    if name.startswith('Steer_'):
        return 'поворот переднего колеса вокруг z через ступицу: угол = угол руля / 16,875 (±32°)'
    if name.startswith('Chains_'):
        return 'цепи противоскольжения на этом колесе: скрыты, пока не надеты из ChainBag; крутятся с колесом'
    if name.startswith('Snow_'):
        return f'снег на фаре {p.get("dims", "")}: масштаб вдоль оси фары 0…1; свет × (1 − 0,85 × количество)'
    if name.startswith('Log_'):
        return 'полено: в печку через Stove_Load'
    if name.startswith('Flare_'):
        return f'фальшфейер: чиркнуть колпачком — около минуты красного света (лампа {name}, тип flare)'
    if name.startswith('Lens_Flare_') or name == 'Lens_Torch':
        return 'стекло фонаря / горящий конец фальшфейера (светится, когда горит)'
    if name.startswith('Curtain_'):
        k = p['range'][1] if p.get('range') else ''
        return f'шторка: растягивается вдоль карниза от края окна; {k} — закрыта (встречается с парной)'
    return p.get('note', '')


