def fmt_v(v, n=3):
    def one(x):
        if not isinstance(x, float):
            return str(x)
        t = f'{x:.{n}f}'.rstrip('0').rstrip('.')
        return '0' if t in ('-0', '') else t
    return '(' + ', '.join(one(x) for x in v) + ')'


def fmt_range(p):
    r = p.get('range')
    if not r:
        return '—'
    if p.get('unit') == 'x':
        return f'×{r[0]}…×{r[1]}'
    u = 'м' if p.get('unit') == 'm' else '°'
    tail = {'end': ', потом снять', 'start': ', вынуть в 0'}.get(p.get('removable'), '')
    return f'{r[0]}…{r[1]} {u}{tail}'


