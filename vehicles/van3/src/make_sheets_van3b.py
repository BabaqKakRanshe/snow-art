def frost_tile():
    """the frost mask on a grey windscreen: four frost amounts side by side"""
    a = np.asarray(Image.open(os.path.join(HERE, 'tex', 'van3', 'T_Van_Frost.png')).convert('RGBA'), np.float32) / 255
    canvas = Image.new('RGB', (900, 600), (10, 10, 12))
    d = ImageDraw.Draw(canvas)
    glass = np.array([0.20, 0.24, 0.27], np.float32)
    for i, f in enumerate((0.2, 0.45, 0.7, 0.95)):
        m = (a[..., 3] > 1 - f)[..., None]
        im = np.where(m, a[..., :3], glass)
        t = Image.fromarray((im * 255).astype(np.uint8)).resize((400, 200), Image.NEAREST)
        x, y = 40 + (i % 2) * 440, 60 + (i // 2) * 260
        canvas.paste(t, (x, y))
        d.text((x, y + 206), f'иней {int(f * 100)} %', fill=MS.INK, font=MS.F(20))
    MS.tag(canvas, 'маска инея на лобовом стекле (T_Van_Frost, альфа = когда замерзает)')
    return canvas


